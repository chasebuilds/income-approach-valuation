/**
 * Benchmark of the calculation library. Run: npm run benchmark
 * Writes BENCHMARK.md with whatever it measures. Nothing is hand-edited.
 */
import { writeFileSync } from 'node:fs';
import { performance } from 'node:perf_hooks';
import { irr, mortgageConstant, npv } from '../src/lib/finance';
import { fourplex } from '../src/data/samples';
import { operatingStatement, parseRentRollCsv, runDcf, sensitivity, summarizeRentRoll } from '../src/lib/valuation';

function timeIt(label: string, iterations: number, fn: () => void): { label: string; iterations: number; perCallUs: number; perSec: number } {
  for (let i = 0; i < Math.min(200, iterations); i++) fn(); // warm up
  const t0 = performance.now();
  for (let i = 0; i < iterations; i++) fn();
  const ms = performance.now() - t0;
  return { label, iterations, perCallUs: (ms * 1000) / iterations, perSec: iterations / (ms / 1000) };
}

const rs = summarizeRentRoll(fourplex.units);
const income = { pgi: rs.marketAnnual, vacancyPct: fourplex.vacancyPct, creditLossPct: fourplex.creditLossPct, otherIncome: fourplex.otherIncome, expenses: fourplex.expenses };
const dcfIn = {
  years: 10,
  pgi: rs.marketAnnual,
  otherIncome: fourplex.otherIncome,
  vacancyPct: fourplex.vacancyPct,
  creditLossPct: fourplex.creditLossPct,
  expenses: fourplex.expenses,
  rentGrowth: 0.025,
  expenseGrowth: 0.03,
  reservePerSf: 0.3,
  sf: rs.sf,
  terminalCap: 0.085,
  sellingCostPct: 0.03,
  discountRate: 0.095,
};
const bigCsv = 'unit,type,sf,rent,market_rent,occupied\n' + Array.from({ length: 5000 }, (_, i) => `U${i},2BR,${700 + (i % 5) * 25},${900 + (i % 7) * 10},${950 + (i % 9) * 10},yes`).join('\n') + '\n';
const flows = [-1000000, ...Array.from({ length: 9 }, () => 85000), 85000 + 1100000];

const results = [
  timeIt('Operating statement (fourplex)', 200000, () => operatingStatement(income)),
  timeIt('DCF, 10 years, with IRR', 20000, () => runDcf(dcfIn)),
  timeIt('IRR, 11 cash flows', 20000, () => irr(flows)),
  timeIt('NPV, 11 cash flows', 200000, () => npv(0.09, flows)),
  timeIt('Sensitivity grid, 5 x 5', 20000, () => sensitivity(income, [0.07, 0.075, 0.08, 0.085, 0.09], [0, 0.025, 0.05, 0.075, 0.1])),
  timeIt('Mortgage constant', 500000, () => mortgageConstant(0.0675, 25)),
  timeIt('Parse 5,000-row rent roll CSV', 20, () => parseRentRollCsv(bigCsv)),
];

// Accuracy: IRR against cases with a known closed-form answer.
const known: [string, number[], number][] = [
  ['one period at 10%', [-100, 110], 0.1],
  ['two periods at 10%', [-100, 0, 121], 0.1],
  ['par bond at 7.5%', [-1000, 75, 75, 75, 1075], 0.075],
  ['one period at -10%', [-100, 90], -0.1],
  ['one period at 100%', [-100, 200], 1],
  ['ten periods, 5% coupon at 5%', [-1000, ...Array.from({ length: 9 }, () => 50), 1050], 0.05],
];
const errs = known.map(([name, cf, want]) => ({ name, err: Math.abs(irr(cf) - want) }));
const maxErr = Math.max(...errs.map((e) => e.err));

const rows = results.map((r) => `| ${r.label} | ${r.iterations.toLocaleString('en-US')} | ${r.perCallUs.toFixed(2)} | ${Math.round(r.perSec).toLocaleString('en-US')} |`).join('\n');
const accRows = errs.map((e) => `| ${e.name} | ${e.err.toExponential(2)} |`).join('\n');

const md = `# Benchmark

Generated by \`npm run benchmark\` (scripts/benchmark.ts). Every number below is what that run printed. Timings change from machine to machine; accuracy figures do not.

- Node ${process.version}
- Run date: ${new Date().toISOString().slice(0, 10)}

## Speed

| Operation | Iterations | Microseconds per call | Calls per second |
|---|---|---|---|
${rows}

## IRR accuracy

Absolute difference between \`irr()\` and the closed-form rate.

| Case | Absolute error |
|---|---|
${accRows}

Largest error across the cases: ${maxErr.toExponential(2)}.
`;
writeFileSync('BENCHMARK.md', md);
console.log(md);
